// SHENNN 书法描字 SVG 路径
//
// 目标风格：贴近 taozhiyy HeroWordmark 的 Pacifico Regular cursive 草书
//   - 连笔：字符之间 y 轴 overlap ~30%，手写体的"一行流"感
//   - 圆头笔画：所有 stroke 端点用曲线闭合（cubic Bézier），不用直线
//   - 末笔收笔：最后一个 N 向右下方甩出长尾巴（呼应 taozhiyo 的 'o' 收笔）
//   - 共享 baseline：所有 path 整体放进 g[transform="translate(0 170)"]，字符基线 ≈ y=0
//
// viewBox: 0 0 720 320
// 字符 height ≈ 200，基线 y=0 在 viewBox 中 y=170
// 字符宽度与间距（带 overlap）:
//   S  : x  60 - 200   (140)
//   H  : x 200 - 320   (120, 左连 S 末)
//   E  : x 320 - 440   (120, 左连 H 末)
//   N1 : x 440 - 560   (120, 左连 E 末)
//   N2 : x 560 - 720   (160, 含 40px 收笔尾巴)

